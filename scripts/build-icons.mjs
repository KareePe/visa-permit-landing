// Generates assets/icons.js: only the Lucide icons this page uses, plus a tiny `lucide.createIcons()`
// that swaps <i data-lucide="name"> for inline SVG (same API as the Lucide UMD build, ~80 KB lighter).
// Icon names are collected from data-lucide="…" in index.html / assets/script.js and from string
// literals in assets/i18n.js that match a Lucide icon. Run with `npm run build:icons` after adding icons.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const ICON_DIR = 'node_modules/lucide-static/icons';
const { version } = JSON.parse(readFileSync('node_modules/lucide-static/package.json', 'utf8'));
const isIcon = name => /^[a-z0-9-]+$/.test(name) && existsSync(`${ICON_DIR}/${name}.svg`);

const names = new Set();
for (const file of ['index.html', 'assets/script.js']) {
  for (const [, name] of readFileSync(file, 'utf8').matchAll(/data-lucide="([a-z0-9-]+)"/g)) names.add(name);
}
for (const [, name] of readFileSync('assets/i18n.js', 'utf8').matchAll(/'([a-z0-9-]+)'/g)) {
  if (isIcon(name)) names.add(name);
}

const icons = {};
for (const name of [...names].sort()) {
  if (!isIcon(name)) throw new Error(`Unknown Lucide icon: ${name}`);
  const svg = readFileSync(`${ICON_DIR}/${name}.svg`, 'utf8');
  icons[name] = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>')).replace(/\s*\n\s*/g, '').replace(/ \/>/g, '/>');
}

writeFileSync('assets/icons.js', `// Generated by scripts/build-icons.mjs — do not edit. Lucide v${version} (ISC license).
const LUCIDE_ICONS = ${JSON.stringify(icons)};
const lucide = {
  createIcons() {
    document.querySelectorAll('i[data-lucide]').forEach(el => {
      const name = el.dataset.lucide, body = LUCIDE_ICONS[name];
      if (!body) return;
      el.outerHTML = \`<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" data-lucide="\${name}" class="lucide lucide-\${name} \${el.className}">\${body}</svg>\`;
    });
  }
};
`);
console.log(`✓ assets/icons.js (${names.size} icons)`);
